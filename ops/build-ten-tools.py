#!/usr/bin/env python3
"""Build this round's review bundle without writing to the existing CoolCode hub."""
import argparse
import hashlib
import json
from pathlib import Path
import re

HERE = Path(__file__).resolve().parent
IDS = ['harbournow', 'screenplaces', 'wikitrails', 'addresschronicle', 'torrentlens',
       'skygeometry', 'budgetmirror', 'movebench', 'canadapulse', 'planehere']

def digest(value):
    return hashlib.sha256(value.encode()).hexdigest()

def module_body(value):
    if re.search(r'^\s*import\s', value, re.M):
        raise ValueError('Worker modules must be self-contained for dashboard paste deployment')
    value = re.sub(r'^export\s+(?=(?:async\s+)?function\b|const\b|class\b|let\b)', '', value, flags=re.M)
    value = re.sub(r'^export\s*\{[^}]*\};?\s*$', '', value, flags=re.M)
    if re.search(r'^\s*export\b', value, re.M):
        raise ValueError('Unexpected Worker export')
    return value

def build(workspace):
    base = (HERE / 'ten-tools-worker-base.js').read_text()
    ids = re.findall(r'"([a-z0-9-]+)"', re.search(r'const toolList = (\[[\s\S]*?\]);', base)[1])
    if not set(IDS).issubset(ids) or len(ids) != len(set(ids)):
        raise ValueError('Reviewed deployed baseline must already register every new ID exactly once')
    worker = base
    marker = "    if(url.pathname.startsWith('/api/halifaxnext/')) return await halifaxApiHandle(request,env,ctx);"
    if worker.count(marker) != 1:
        raise ValueError('Baseline dispatcher changed; review rather than overwriting')
    worker = worker.replace(marker, marker + "\n    if(url.pathname.startsWith('/api/screenplaces/')) return await screenplacesApiHandle(request,env,ctx);\n    if(url.pathname.startsWith('/api/planehere/')) return await planehereApiHandle(request,env,ctx);")
    status = 'corporateghosts:Boolean(env.ISED_CORPORATIONS_API_KEY)'
    if worker.count(status) != 1:
        raise ValueError('Baseline status route changed')
    worker = worker.replace(status, status + ',screenplaces:Boolean(env.TMDB_READ_ACCESS_TOKEN),planehere:true,planehere_key:Boolean(env.ADSBLOL_API_KEY)')
    modules = []
    for name in ['screenplaces', 'planehere']:
        relative = 'services/gateway.mjs' if name == 'screenplaces' else 'services/gateway.js'
        source = (workspace / name / relative).read_text()
        modules.append({'repo': f'jsdyer/{name}', 'path': relative, 'sha256': digest(source)})
        worker += '\n\n// ' + name + ' public API module; source: ' + relative + '\n' + module_body(source)
    worker = worker.replace('// Generated by scripts/sync_operations.py; edit worker.template.js and data/tools.json.',
        '// Ten-tool release bundle: reviewed deployed baseline plus new app-owned gateways.\n// Rebuild with ops/build-ten-tools.py; existing hub repository remains unchanged.', 1)
    (HERE / 'ten-tools-worker.js').write_text(worker)
    tools = []
    for name in IDS:
        tool = json.loads((workspace / name / 'tool.json').read_text())
        if tool['id'] != name or tool['source'] != f'https://github.com/jsdyer/{name}':
            raise ValueError('Tool identity mismatch: ' + name)
        tools.append(tool)
    (HERE / 'ten-tools-catalogue.json').write_text(json.dumps(tools, indent=2, ensure_ascii=False) + '\n')
    report = {'schema': 'coolcode.ten-tools-release.v1', 'repository_scope': IDS,
              'existing_repositories_modified': False, 'baseline_sha256': digest(base),
              'worker_sha256': digest(worker), 'registered_ids': len(ids), 'modules': modules,
              'worker_deployed': False, 'vps_deployed': False,
              'hub_catalogue_sitemap_watchdog': 'Prepared separately; not applied because this round is limited to the ten new repositories.'}
    (HERE / 'ten-tools-integration.json').write_text(json.dumps(report, indent=2) + '\n')
    print(json.dumps({'worker_sha256': digest(worker), 'registered_ids': len(ids), 'tools': len(tools)}))

if __name__ == '__main__':
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument('--checkouts-root', type=Path, default=HERE.parent.parent)
    build(parser.parse_args().checkouts_root)
